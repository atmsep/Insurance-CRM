const COMBINING_DIACRITICS = /[̀-ͯ]/g; // τόνος, διαλυτικά, etc.

function normalizeGreekName(name: string): string {
  return name.normalize("NFD").replace(COMBINING_DIACRITICS, "").toUpperCase().trim();
}

const NAME_DAY_LOOKUP: Map<string, { month: number; day: number }> = new Map();
for (const [names, month, day] of NAME_DAY_ENTRIES) {
  for (const name of names.split(",")) {
    NAME_DAY_LOOKUP.set(normalizeGreekName(name), { month, day });
  }
}

export function getNameDay(firstName: string): { month: number; day: number } | null {
  if (!firstName) return null;
  return NAME_DAY_LOOKUP.get(normalizeGreekName(firstName)) ?? null;
}
